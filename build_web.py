#!/usr/bin/env python3
"""Generate the browser app's code bundle.

The static app (Pyodide) needs the pure-Python parsers, HTML templates and rule JSON in
its in-memory filesystem. Rather than fetch each file at runtime, we bundle them all into
`py-bundle.js` as `window.PBIP_FILES` (a path -> text map). This matters because some
corporate proxies (e.g. Zscaler) block `.py` downloads with HTTP 403 — bundling into a
`.js` file sidesteps that entirely, so the app works on locked-down networks.

Re-run this whenever the set/contents of parser files, templates or rules change.

Usage:  python build_web.py
Output:
  - py-bundle.js   window.PBIP_FILES = { "<repo-path>": "<file text>", ... }  (what the app loads)
  - manifest.json  sorted JSON array of the bundled paths (reference / CI)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent              # repo root (also the site root)

# files the in-browser Python needs (all pure-stdlib; no Desktop / no network)
SCRIPTS = [
    "load_tmdl.py", "mquery.py", "build_lineage.py",
    "find_unused_artifacts.py", "evaluate_bpa.py",
    "render_report.py", "fonts.py",
]
TEMPLATES = [
    "bpa-report-template.html", "unused-report-template.html",
    "lineage-report-template.html",
]
RULES = [
    "BPARules-custom-extended.json", "BPARules-measurekiller.json",
    "BPARules-PowerBI.json", "BPARules-standard.json",
]


def build():
    manifest = ["pyagent.py", "scripts/assets/ia-fonts.css"]
    manifest += [f"scripts/{n}" for n in SCRIPTS]
    manifest += [f"templates/{n}" for n in TEMPLATES]
    manifest += [f"rules/{n}" for n in RULES]
    manifest = sorted(manifest)

    missing = [m for m in manifest if not (ROOT / m).is_file()]
    if missing:
        raise SystemExit("manifest references missing files:\n  " + "\n  ".join(missing))

    # manifest.json — the list of bundled paths (kept for reference / CI)
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=0), encoding="utf-8")

    # py-bundle.js — every file inlined as window.PBIP_FILES so the app loads its Python
    # without fetching .py files (which some corporate proxies block with HTTP 403).
    bundle = {rel: (ROOT / rel).read_text(encoding="utf-8") for rel in manifest}
    (ROOT / "py-bundle.js").write_text(
        "// AUTO-GENERATED by build_web.py — do not edit by hand.\n"
        "// Regenerate (python build_web.py) whenever a parser/template/rule file changes.\n"
        "// Inlines the app's Python/templates/rules so nothing is fetched as a .py file\n"
        "// (some corporate proxies, e.g. Zscaler, block .py downloads with HTTP 403).\n"
        "window.PBIP_FILES = " + json.dumps(bundle, ensure_ascii=False) + ";\n",
        encoding="utf-8")

    total = sum(len(v) for v in bundle.values())
    print(f"Wrote py-bundle.js ({len(bundle)} files, {total/1024:.0f} KB of source) "
          f"and manifest.json:")
    for m in manifest:
        print("  ", m)


if __name__ == "__main__":
    build()
